def language_of(path: str) -> str | None:
    p = PurePosixPath(path)
    name = p.name.lower()
    if name == "dockerfile" or name.endswith(".dockerfile") or name.startswith("dockerfile."):
        return "dockerfile"
    if name == "jenkinsfile":
        return "groovy"
    return EXT_LANG.get(p.suffix.lower())


def is_test_path(path: str) -> bool:
    low = path.replace("\\", "/")
    if _TEST_RE.search(low):
        return True
    lang = language_of(low)
    return bool(_TEST_DIR_RE.search(low)) and lang in SOURCE_LANGS and lang not in ("html_css", "sql")


def ignore_reason(path: str, size: int, max_bytes: int) -> str | None:
    """Return why a path is skipped (recorded in the scope manifest) or None to scan it."""
    low = path.replace("\\", "/")
    name = PurePosixPath(low).name
    lname = name.lower()
    if any(("/" + d) in ("/" + low) for d in VENDOR_DIRS):
        return "vendored/third-party directory"
    if any(("/" + d) in ("/" + low) for d in GENERATED_DIRS):
        return "build output / generated directory"
    if name in LOCKFILES:
        return "dependency lockfile"
    ext = PurePosixPath(lname).suffix
    if ext in BINARY_EXT:
        return "binary or non-source asset"
    if re.search(r"\.(min|bundle|chunk)\.(js|css)$", lname) or lname.endswith(("_pb2.py", "_pb2_grpc.py", ".pb.go", ".generated.ts", ".d.ts")):
        return "minified/generated artifact"
    if ext in (".md", ".rst", ".txt", ".adoc") and name not in MANIFESTS and not lname.startswith("requirements"):
        return "documentation (not used as implementation evidence)"
    if size > max_bytes:
        return f"file larger than {max_bytes} bytes"
    lang = language_of(low)
    if lang is None and lname not in CONFIG_NAMES and name not in MANIFESTS and lname not in ("procfile",):
        return "unsupported file type"
    return None


def file_kind(path: str, head_text: str = "") -> str:
    low = path.replace("\\", "/")
    name = PurePosixPath(low).name
    if any(("/" + d) in ("/" + low) for d in VENDOR_DIRS):
        return "vendor"
    head = head_text[:600].lower()
    if any(m in head for m in GENERATED_MARKERS):
        return "generated"
    if name in MANIFESTS or (name.lower().startswith("requirements") and name.lower().endswith(".txt")):
        return "manifest"
    if is_test_path(low):
        return "test"
    lang = language_of(low)
    if lang in ("markdown", "rst", "text"):
        return "docs"
    if lang in ("yaml", "json", "toml", "ini", "terraform", "xml", "gradle", "dockerfile", "groovy") or name.lower() in CONFIG_NAMES:
        return "config"
    return "implementation"


def matches_scope(path: str, include: list[str], exclude: list[str]) -> bool:
    def _m(pattern: str) -> bool:
        pat = pattern.strip().lstrip("/")
        if not pat:
            return False
        if pat.endswith("/"):
            return path.startswith(pat) or ("/" + pat) in ("/" + path)
        return fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(path, pat.rstrip("/") + "/*") or path.startswith(pat.rstrip("/") + "/")
    if include and not any(_m(p) for p in include):
        return False
    if exclude and any(_m(p) for p in exclude):
        return False
    return True
